import { createHash } from 'node:crypto'
import { readFile, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const XN_PTTS_REVISION = '4398678425e1b3d48d525024257830aec989bc58'
const EXPECTED_MODULE_SHA256 = 'c58e462ffae81094a8ae4796dde4f5ef493667afab8642fa30e6410b8dcd099d'
const EXPECTED_WASM_SHA256 = '83a0cd64fe133a146714ae7a8dd369cb26b19e9a0b0b2732e963a024795b5a79'
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const outputs = [
  resolve(root, 'src/lib/speech/pocketTtsXnModule.js'),
  resolve(root, 'src/lib/speech/pocketTtsXnWasm1.js'),
  resolve(root, 'src/lib/speech/pocketTtsXnWasm2.js'),
]

function sha256(value) {
  return createHash('sha256').update(value).digest('hex')
}

function generatedFiles(moduleSource, wasm) {
  const moduleHash = sha256(moduleSource)
  const wasmHash = sha256(wasm)
  if (moduleHash !== EXPECTED_MODULE_SHA256) {
    throw new Error(`Unexpected XN module SHA-256: ${moduleHash}`)
  }
  if (wasmHash !== EXPECTED_WASM_SHA256) {
    throw new Error(`Unexpected XN runtime SHA-256: ${wasmHash}`)
  }
  const encoded = wasm.toString('base64')
  const parts = [encoded.slice(0, 750_000), encoded.slice(750_000)]
  if (parts.some((part) => part.length >= 1_048_000 || part.length % 4 !== 0)) {
    throw new Error('The embedded Wasm chunks do not fit the app source contract.')
  }
  return [
    `// Generated by scripts/embed-xn-runtime.mjs from XN Pocket TTS ${XN_PTTS_REVISION}.\n`
      + `// Module SHA-256: ${moduleHash}\n// Wasm SHA-256: ${wasmHash}\n`
      + `export const XN_PTTS_MODULE_SOURCE = ${JSON.stringify(moduleSource)}\n`
      + `export const XN_PTTS_WASM_BYTES = ${wasm.byteLength}\n`
      + `export const XN_PTTS_WASM_SHA256 = ${JSON.stringify(wasmHash)}\n`,
    `// Generated by scripts/embed-xn-runtime.mjs.\nexport const XN_PTTS_WASM_BASE64_1 = ${JSON.stringify(parts[0])}\n`,
    `// Generated by scripts/embed-xn-runtime.mjs.\nexport const XN_PTTS_WASM_BASE64_2 = ${JSON.stringify(parts[1])}\n`,
  ]
}

function exportedString(source, name) {
  const marker = `export const ${name} = `
  const line = source.split('\n').find((value) => value.startsWith(marker))
  if (!line) throw new Error(`Missing generated export ${name}.`)
  return JSON.parse(line.slice(marker.length))
}

const check = process.argv.includes('--check')
const paths = process.argv.slice(2).filter((value) => value !== '--check')
let moduleSource
let wasm
if (paths.length === 0 && check) {
  const current = await Promise.all(outputs.map((path) => readFile(path, 'utf8')))
  moduleSource = exportedString(current[0], 'XN_PTTS_MODULE_SOURCE')
  wasm = Buffer.from(
    exportedString(current[1], 'XN_PTTS_WASM_BASE64_1')
      + exportedString(current[2], 'XN_PTTS_WASM_BASE64_2'),
    'base64',
  )
} else if (paths.length === 2) {
  [moduleSource, wasm] = await Promise.all([
    readFile(resolve(paths[0]), 'utf8'),
    readFile(resolve(paths[1])),
  ])
} else {
  throw new Error('Usage: node scripts/embed-xn-runtime.mjs [--check] <ptts_wasm.js> <ptts_wasm_bg.wasm>')
}

const generated = generatedFiles(moduleSource, wasm)
if (check) {
  const current = await Promise.all(outputs.map((path) => readFile(path, 'utf8')))
  if (current.some((value, index) => value !== generated[index])) {
    throw new Error('Embedded XN runtime is stale or differs from its pinned inputs.')
  }
} else await Promise.all(outputs.map((path, index) => writeFile(path, generated[index])))
