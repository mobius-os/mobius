import { createHash } from 'node:crypto'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

// XN's Pocket TTS runtime ships as wasm-bindgen output: an ES module plus its
// companion Wasm binary. Möbius serves both as ordinary same-origin assets so
// the speech worker can load them under `script-src 'self'`. Embedding them as
// JavaScript string/base64 literals instead would force `blob:` into the
// shell's script policy, because the worker would have to rebuild them into
// blob URLs at runtime.
const XN_PTTS_REVISION = '4398678425e1b3d48d525024257830aec989bc58 + Möbius v2/cloning/streaming adapter'
const EXPECTED_MODULE_SHA256 = 'ad08cdd24e0664b6085079d239ff7bb10d4443eee4dfea956d825d0696493563'
const EXPECTED_WASM_SHA256 = 'e11ad32a0e454e5fed870efa186c2166c92fc0e674de7dc94882a27e62910768'
// The adapted runtime is a pure function of the pinned upstream module, so its
// own hash is pinned too. That lets `--check` verify the shipped files without
// needing the upstream inputs on disk.
const EXPECTED_RUNTIME_SHA256 = 'f36b4dffc120ca6a49c94a491efc1028582fcae2bc97123d679a8c9b95486aaa'
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const runtimePath = resolve(root, 'src/lib/speech/pocketTtsXnRuntime.js')
const wasmPath = resolve(root, 'public/speech/pocket-tts-xn.wasm')

function sha256(value) {
  return createHash('sha256').update(value).digest('hex')
}

// Wasm-bindgen's ordinary Uint8Array bridge copies the whole model into the
// Wasm heap just before Rust opens it. For a 148 MB model that briefly keeps
// both the JavaScript buffer and the Wasm copy alive. These three exports let
// the worker pre-allocate the final Wasm buffer, stream cached chunks straight
// into it, and hand that exact allocation to Rust. Applying the adaptation
// here, at generation time, keeps the shipped runtime a plain readable module
// instead of a string the worker rewrites on every load.
const ADAPTER_ANCHOR = '}\nif (Symbol.dispose) Model.prototype[Symbol.dispose] = Model.prototype.free;'
const ADAPTER = `}

export function allocate_model_weights(length) {
    if (!Number.isSafeInteger(length) || length < 1) throw new Error('Invalid model allocation.');
    const ptr = wasm.__wbindgen_malloc(length, 1) >>> 0;
    return { ptr, length, bytes: getUint8ArrayMemory0().subarray(ptr, ptr + length) };
}

export function model_from_allocated_weights(allocation, quant, enableCloning) {
    const ptr0 = allocation.ptr >>> 0;
    const len0 = allocation.length >>> 0;
    if (!ptr0 || !len0) throw new Error('The streamed model allocation is unavailable.');
    try {
        // This XN adapter consumes the exact Wasm allocation rather than
        // cloning all model weights into a second Rust-owned buffer.
        return Model.fromRawModelWeights(ptr0, len0, quant, enableCloning);
    } finally {
        allocation.ptr = 0;
        allocation.length = 0;
        allocation.bytes = null;
    }
}

export function free_allocated_model_weights(allocation) {
    const ptr = allocation?.ptr >>> 0;
    const length = allocation?.length >>> 0;
    if (ptr && length) wasm.__wbindgen_free(ptr, length, 1);
    if (allocation) {
        allocation.ptr = 0;
        allocation.length = 0;
        allocation.bytes = null;
    }
}
if (Symbol.dispose) Model.prototype[Symbol.dispose] = Model.prototype.free;`

function assertSha(content, expected, label) {
  const actual = sha256(content)
  if (actual !== expected) {
    throw new Error(`${label}: expected SHA-256 ${expected}, got ${actual}`)
  }
}

function adaptedRuntime(moduleSource) {
  assertSha(moduleSource, EXPECTED_MODULE_SHA256, 'upstream ptts_wasm.js')
  if (!moduleSource.includes(ADAPTER_ANCHOR)) {
    throw new Error('The pinned XN module no longer exposes the streaming adapter anchor.')
  }
  return `// Generated by scripts/embed-xn-runtime.mjs from XN Pocket TTS ${XN_PTTS_REVISION}.\n`
    + `// Upstream module SHA-256: ${EXPECTED_MODULE_SHA256}\n`
    + `// Companion binary: public/speech/pocket-tts-xn.wasm (SHA-256 ${EXPECTED_WASM_SHA256})\n`
    + moduleSource.replace(ADAPTER_ANCHOR, ADAPTER)
}

const check = process.argv.includes('--check')
const paths = process.argv.slice(2).filter((value) => value !== '--check')

if (paths.length === 2) {
  const [moduleSource, wasm] = await Promise.all([
    readFile(resolve(paths[0]), 'utf8'),
    readFile(resolve(paths[1])),
  ])
  const runtime = adaptedRuntime(moduleSource)
  assertSha(wasm, EXPECTED_WASM_SHA256, 'upstream ptts_wasm_bg.wasm')
  assertSha(runtime, EXPECTED_RUNTIME_SHA256, 'adapted runtime')
  if (!check) {
    await mkdir(dirname(wasmPath), { recursive: true })
    await Promise.all([writeFile(runtimePath, runtime), writeFile(wasmPath, wasm)])
  }
} else if (paths.length || !check) {
  throw new Error('Usage: node scripts/embed-xn-runtime.mjs [--check] <ptts_wasm.js> <ptts_wasm_bg.wasm>')
}

// Every mode ends by proving the files that actually ship match their pins.
const [shippedRuntime, shippedWasm] = await Promise.all([
  readFile(runtimePath, 'utf8'),
  readFile(wasmPath),
])
assertSha(shippedRuntime, EXPECTED_RUNTIME_SHA256, 'src/lib/speech/pocketTtsXnRuntime.js')
assertSha(shippedWasm, EXPECTED_WASM_SHA256, 'public/speech/pocket-tts-xn.wasm')
