import { build } from 'rolldown'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

import { enterBuildAdmission } from './build-admission.mjs'


enterBuildAdmission()

// The speech worker is served from public/speech/ as an ordinary same-origin
// script, alongside the Wasm binary it loads. Shipping it as a JavaScript
// string that the page turns into a blob: URL would need `blob:` in the
// shell's script-src, and the worker would fail to start without it.
const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const outputPath = join(root, 'public/speech/pocket-tts-worker.js')
const result = await build({
  input: join(root, 'src/lib/speech/pocketTtsWorkerEntry.js'),
  platform: 'browser',
  // Wasm-bindgen's generated init falls back to `new URL(..., import.meta.url)`
  // only when called with no argument. The worker always passes the served
  // binary's URL explicitly, so that branch is unreachable here and the iife
  // format's empty-object substitution is safe rather than a silent hazard.
  transform: { define: { 'import.meta': '{}' } },
  output: { format: 'iife', minify: true },
})
const generated = `// Generated by scripts/build-tts-worker.mjs. Do not edit.\n${result.output[0].code}`

if (process.argv.includes('--check')) {
  let current = ''
  try { current = await readFile(outputPath, 'utf8') } catch {}
  if (current !== generated) {
    console.error('public/speech/pocket-tts-worker.js is stale; run npm run speech-worker:build')
    process.exitCode = 1
  }
} else {
  await mkdir(dirname(outputPath), { recursive: true })
  await writeFile(outputPath, generated)
}
