import { build } from 'rolldown'
import { readFile, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const outputPath = join(root, 'src/lib/speech/pocketTtsWorkerSource.js')
const result = await build({
  input: join(root, 'src/lib/speech/pocketTtsWorkerEntry.js'),
  platform: 'browser',
  output: { format: 'iife', minify: true },
})
const source = result.output[0].code
const generated = `// Generated by scripts/build-tts-worker.mjs.\nexport const POCKET_TTS_WORKER_SOURCE = ${JSON.stringify(source)}\n`

if (process.argv.includes('--check')) {
  let current = ''
  try { current = await readFile(outputPath, 'utf8') } catch {}
  if (current !== generated) {
    console.error('pocketTtsWorkerSource.js is stale; run npm run speech-worker:build')
    process.exitCode = 1
  }
} else await writeFile(outputPath, generated)
