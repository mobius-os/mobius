# Derived views. Import these instead of maintaining parallel policies.
GITIGNORE = "\n".join(line for entry in REGISTRY for line in entry.ignore_lines) + "\n"
MANAGED_RUNTIME_PATHS = tuple(
  spec for entry in REGISTRY for spec in entry.untrack_pathspecs
)
MERGED_NON_SOURCE = frozenset(
  entry.name for entry in REGISTRY if entry.drop_from_merged_tree
)
