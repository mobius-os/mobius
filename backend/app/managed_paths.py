"""Install-managed paths and their distinct Git/installer policies.

Ignore rules prevent new runtime files from entering app history. Untrack
pathspecs also remove legacy tracked files from the index, while merged-tree
drops exclude exact installer-owned names from source writes. These policies
have intentionally different memberships; declare each path's roles together
rather than inferring one policy from another.
"""

from __future__ import annotations

from dataclasses import dataclass

STATIC_ASSETS_MANIFEST = ".mobius-static-assets.json"


@dataclass(frozen=True)
class ManagedPath:
  """One path or group with explicit policy roles.

  Ignore lines include comments and use gitignore syntax. Untrack selectors
  use Git pathspec syntax; their order is irrelevant. Entries dropped from
  installer source handling use an exact tree key as their name.
  """

  name: str
  ignore_lines: tuple[str, ...] = ()
  untrack_pathspecs: tuple[str, ...] = ()
  drop_from_merged_tree: bool = False


# Order preserves the generated ignore file; entries without ignore lines
# participate only in untracking or merged-tree filtering.
